def parse_symbol(symbol):
    """'D7' -> ('D', 7); 'I' -> ('I', 0). Raises ValueError for anything
    SymmetryMatrix::Init() would refuse."""
    s = (symbol or "C1").strip().upper()
    if not s or s[0] not in "CDTOI":
        raise ValueError("unknown symmetry '{}'".format(symbol))
    n = 0
    if len(s) > 1:
        if not s[1:].isdigit():
            raise ValueError("unknown symmetry '{}'".format(symbol))
        n = int(s[1:])
    if s[0] in "CD" and n == 0:
        raise ValueError("{} symmetry needs a fold number".format(s[0]))
    return s[0], n


def matrices(symbol):
    """SymmetryMatrix::Init(): the rotation matrices of the point group."""
    kind, n = parse_symbol(symbol)
    if kind == "C":
        out = []
        for i in range(n):
            a = 2.0 * math.pi * i / n
            out.append(_from_values((math.cos(a), math.sin(a), 0.0, -math.sin(a), math.cos(a), 0.0, 0.0, 0.0, 1.0)))
        return out
    if kind == "D":
        out = []
        for i in range(n):
            a = 2.0 * math.pi * i / n
            out.append(_from_values((math.cos(a), math.sin(a), 0.0, -math.sin(a), math.cos(a), 0.0, 0.0, 0.0, 1.0)))
        for i in range(n):
            a = 2.0 * math.pi * i / n
            out.append(_from_values((math.cos(a), -math.sin(a), 0.0, -math.sin(a), -math.cos(a), 0.0, 0.0, 0.0, -1.0)))
        return out
    if kind == "T":
        table = _T2 if n == 2 else _T
    elif kind == "O":
        table = _O
    else:
        table = _I2 if n == 2 else _I
    return [_from_values(v) for v in table]


def euler_matrix(phi, theta, psi):
    """RotationMatrix::SetToEulerRotation(phi, theta, psi), degrees."""
    cp, sp = math.cos(math.radians(phi)), math.sin(math.radians(phi))
    ct, st = math.cos(math.radians(theta)), math.sin(math.radians(theta))
    cs, ss = math.cos(math.radians(psi)), math.sin(math.radians(psi))
    return ((cp * ct * cs - sp * ss, -cp * ct * ss - sp * cs, st * cp),
            (sp * ct * cs + cp * ss, -sp * ct * ss + cp * cs, st * sp),
            (-st * cs, st * ss, ct))


def matmul(a, b):
    return tuple(tuple(sum(a[i][k] * b[k][j] for k in range(3)) for j in range(3)) for i in range(3))


def rotate(m, v):
    """RotationMatrix::RotateCoords: m . v."""
    return tuple(m[i][0] * v[0] + m[i][1] * v[1] + m[i][2] * v[2] for i in range(3))


def projection_theta_deg(x, y):
    """ConvertProjectionXYToThetaInDegrees: the tilt of a unit vector from its x, y."""
    return math.degrees(math.asin(min(1.0, math.sqrt(x * x + y * y))))


def projection_phi_deg(x, y):
    """ConvertXYToPhiInDegrees."""
    if x == 0 and y == 0:
        return 0.0
    return math.degrees(math.atan2(y, x))


def symmetry_related_views(phi, theta, psi, symbol):
    """Refinement::FillAngularDistributionHistogram()'s inner loop: the
    (theta, phi) in degrees of the north pole under every symmetry-related
    orientation, folded onto the northern hemisphere."""
    em = euler_matrix(phi, theta, psi)
    out = []
    for rm in matrices(symbol):
        x, y, z = rotate(matmul(rm, em), (0.0, 0.0, 1.0))
        if z < 0.0:
            x, y, z = -x, -y, -z
        out.append((projection_theta_deg(x, y), projection_phi_deg(x, y)))
    return out
